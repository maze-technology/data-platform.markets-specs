#!/usr/bin/env bash
# Scaffold a Cargo crate from buf/prost(+tonic) output for Kellnr publish.
set -euo pipefail

OUT="${1:-build/generated/rust}"
SRC_RS="${OUT}/src"
mkdir -p "${SRC_RS}"

ROOT_NAME="$(grep -E 'rootProject.name' settings.gradle | sed -E 's/.*"([^"]+)".*/\1/')"
# Maven group (e.g. tech.maze.dtos.dataplatform) → crate prefix dtos-dataplatform-<artifact>
GROUP="$(grep -E '^group\s*=' build.gradle | head -1 | sed -E 's/^group\s*=\s*"([^"]+)".*/\1/' || true)"
if [[ "${GROUP}" =~ ^tech\.maze\.dtos\.([a-z0-9]+)$ ]]; then
  DOMAIN="${BASH_REMATCH[1]}"
  CRATE_NAME="dtos-${DOMAIN}-${ROOT_NAME}"
elif [[ "${ROOT_NAME}" == *.* ]]; then
  # Legacy: rootProject.name was the full artifact (dtos.ohlcvs)
  CRATE_NAME="$(echo "${ROOT_NAME}" | tr '.' '-' | tr '[:upper:]' '[:lower:]')"
else
  CRATE_NAME="$(echo "${ROOT_NAME}" | tr '.' '-' | tr '[:upper:]' '[:lower:]')"
fi
CRATE_NAME="$(echo "${CRATE_NAME}" | tr '[:upper:]' '[:lower:]')"

VERSION="$(grep -E '^version' gradle.properties | head -1 | sed -E 's/.*=\s*//' | tr -d '[:space:]' | sed 's/-SNAPSHOT//')"
VERSION="${VERSION:-0.1.0}"
if [ -n "${CI_COMMIT_TAG:-}" ]; then
  VERSION="${CI_COMMIT_TAG#v}"
fi

# Prost files are named like tech.maze.dtos.helloworld.models.rs and expect
# sibling modules (super::models) and shared parents (super::super::commons::…).
# Tonic stubs (*tonic.rs) are include!()'d from the companion prost file — do
# not register them as modules.
mapfile -t files < <(
  find "${SRC_RS}" -type f -name '*.rs' ! -name 'lib.rs' ! -name '*tonic.rs' | sort
)

NEED_TONIC=0
if find "${SRC_RS}" -type f -name '*tonic.rs' | grep -q .; then
  NEED_TONIC=1
fi

{
  echo "// @generated by scripts/rust-crate.sh — do not edit."
  echo "#![allow(dead_code, unused_imports, clippy::all)]"
  echo
  if [ "${#files[@]}" -eq 0 ]; then
    echo "//! DTO crate from ${ROOT_NAME} specs (proto → prost)."
    echo "pub const CRATE_NAME: &str = \"${CRATE_NAME}\";"
    echo "pub const CRATE_VERSION: &str = env!(\"CARGO_PKG_VERSION\");"
  else
    # Nest modules to match protobuf package paths so prost `super::` / `super::super::`
    # refs resolve (e.g. markets.requests → commons.search). Keep .rs files flat under
    # src/ and include!() them — cargo package omits empty nested dirs, which broke
    # the earlier #[path = "../…"] layout (see f67702f). Flattening by leaf name also
    # collided when commons.search and markets.search both became `pub mod search`.
    rels=()
    for f in "${files[@]}"; do
      rels+=("${f#${SRC_RS}/}")
    done
    SRC_RS="${SRC_RS}" python3 - "${rels[@]}" <<'PY'
import sys

files = sys.argv[1:]
tree: dict = {}
for rel in files:
    if not rel.endswith(".rs"):
        raise SystemExit(f"expected .rs file, got {rel!r}")
    parts = rel[: -len(".rs")].split(".")
    if len(parts) < 2:
        raise SystemExit(f"prost file needs package.path.leaf.rs, got {rel!r}")
    node = tree
    for part in parts[:-1]:
        child = node.get(part)
        if isinstance(child, str):
            raise SystemExit(f"path conflict at {part} for {rel}")
        if child is None:
            child = {}
            node[part] = child
        node = child
    leaf = parts[-1]
    if leaf in node and not isinstance(node[leaf], str):
        raise SystemExit(f"leaf {leaf} conflicts with nested module for {rel}")
    node[leaf] = rel


def emit(node: dict, indent: int = 0) -> None:
    pad = "  " * indent
    for key in sorted(node):
        val = node[key]
        if isinstance(val, str):
            print(f"{pad}pub mod {key} {{")
            print(f'{pad}  include!("{val}");')
            print(f"{pad}}}")
        else:
            print(f"{pad}pub mod {key} {{")
            emit(val, indent + 1)
            print(f"{pad}}}")


emit(tree)
PY
  fi
} > "${SRC_RS}/lib.rs"

DEPS=$'prost = "0.13"\nprost-types = "0.13"\nbytes = "1"'
if [ "${NEED_TONIC}" -eq 1 ]; then
  DEPS+=$'\ntonic = { version = "0.12", default-features = false, features = ["codegen", "transport", "prost"] }\nhttp = "1"\ntokio = { version = "1", features = ["macros", "rt"] }\nasync-trait = "0.1"'
fi

cat > "${OUT}/Cargo.toml" <<TOML
[package]
name = "${CRATE_NAME}"
version = "${VERSION}"
edition = "2021"
description = "Maze DTO crate generated from ${GROUP:-tech.maze}:${ROOT_NAME} specs"
license = "MIT"
publish = ["maze"]

[dependencies]
${DEPS}

[package.metadata.docs.rs]
all-features = true
TOML

echo "rust crate ready: ${OUT} name=${CRATE_NAME} version=${VERSION} modules=${#files[@]} tonic=${NEED_TONIC} group=${GROUP:-}"
